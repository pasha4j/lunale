#!/usr/bin/env python3
"""Builds espanle/world.js, the world map for thelunale.com/espanle/.

Takes Natural Earth 1:50m countries from world-atlas, Douglas-Peucker
simplifies each TopoJSON arc (arcs stay shared, so borders still line up),
re-quantizes, and drops Antarctica and the unused `land` object. Written as a script
(window.WORLD_TOPO = ...) rather than JSON so the page also works from file://.

Standard library only.

    curl -sSLO https://cdn.jsdelivr.net/npm/world-atlas@2.0.2/countries-50m.json
    python3 scripts/espanle/simplify_map.py countries-50m.json espanle/world.js 0.03 2e4
"""
import json
import math
import sys

src, dst, tol = sys.argv[1], sys.argv[2], float(sys.argv[3])  # tol in degrees
Q = float(sys.argv[4]) if len(sys.argv) > 4 else 2e4

d = json.load(open(src))
t = d['transform']
sx, sy = t['scale']
tx, ty = t['translate']


def decode(arc):
    x = y = 0
    out = []
    for dx, dy in arc:
        x += dx
        y += dy
        out.append((x * sx + tx, y * sy + ty))
    return out


def dp(pts, tol):
    if len(pts) < 3:
        return pts
    keep = [False] * len(pts)
    keep[0] = keep[-1] = True
    stack = [(0, len(pts) - 1)]
    while stack:
        a, b = stack.pop()
        ax, ay = pts[a]
        bx, by = pts[b]
        dx, dy = bx - ax, by - ay
        L = math.hypot(dx, dy)
        best, bi = -1, -1
        for i in range(a + 1, b):
            px, py = pts[i]
            dist = math.hypot(px - ax, py - ay) if L == 0 else abs(dy * px - dx * py + bx * ay - by * ax) / L
            if dist > best:
                best, bi = dist, i
        if best > tol:
            keep[bi] = True
            stack += [(a, bi), (bi, b)]
    res = [p for p, k in zip(pts, keep) if k]
    if pts[0] == pts[-1] and len(res) < 4 and len(pts) >= 4:
        # closed ring collapsed: keep a triangle so tiny islands survive
        n = len(pts) - 1
        res = [pts[0], pts[n // 3], pts[2 * n // 3], pts[0]]
    return res


nsx, nsy = 360 / (Q - 1), 180 / (Q - 1)


def encode(pts):
    out = []
    px = py = 0
    prev = None
    for x, y in pts:
        qx = round((x + 180) / nsx)
        qy = round((y + 90) / nsy)
        if prev == (qx, qy):
            continue
        out.append([qx - px, qy - py])
        px, py = qx, qy
        prev = (qx, qy)
    if len(out) == 1:
        out.append([0, 0])
    return out


d['arcs'] = [encode(dp(decode(a), tol)) for a in d['arcs']]
d['transform'] = {'scale': [nsx, nsy], 'translate': [-180, -90]}
geoms = d['objects']['countries']['geometries']
d['objects']['countries']['geometries'] = [g for g in geoms if g['properties']['name'] != 'Antarctica']
d['objects'].pop('land', None)
with open(dst, 'w') as f:
    f.write('// Generated by scripts/espanle/simplify_map.py; Natural Earth 1:50m via world-atlas.\nwindow.WORLD_TOPO = ')
    json.dump(d, f, separators=(',', ':'))
    f.write(';\n')
